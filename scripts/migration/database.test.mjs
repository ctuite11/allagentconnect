import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { PGlite } from '@electric-sql/pglite';

const ref = 'zzzzzzzzzzzzzzzzzzzz';
const script = readFileSync(new URL('./lock-destination.sql', import.meta.url), 'utf8');
const lock = script.replace('REPLACE_WITH_NEW_PROJECT_REF', ref);

test('destination SQL lock in offline PostgreSQL with mocked Supabase services', async (t) => {
  const db = new PGlite();
  try {
    await db.exec(`
      CREATE ROLE anon; CREATE ROLE authenticated; CREATE ROLE service_role;
      CREATE SCHEMA cron; CREATE SCHEMA net; CREATE SCHEMA supabase_functions; CREATE SCHEMA business;
      CREATE TABLE cron.job(jobid bigint PRIMARY KEY, jobname text, schedule text, active boolean, command text);
      INSERT INTO cron.job VALUES (1,'mail','* * * * *',true,'SELECT public.invoke_worker()'),
                                 (2,'paused','* * * * *',false,'SELECT 1');
      CREATE FUNCTION cron.alter_job(job_id bigint, active boolean) RETURNS void LANGUAGE sql AS
        'UPDATE cron.job SET active = $2 WHERE jobid = $1';
      CREATE TABLE net.http_request_queue(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                         url text, headers jsonb, body jsonb);
      CREATE FUNCTION net.http_post(url text, headers jsonb DEFAULT '{}'::jsonb, body jsonb DEFAULT '{}'::jsonb)
      RETURNS bigint LANGUAGE plpgsql AS $$ DECLARE request_id bigint; BEGIN
        INSERT INTO net.http_request_queue(url,headers,body) VALUES($1,$2,$3) RETURNING id INTO request_id;
        RETURN request_id; END; $$;
      INSERT INTO net.http_request_queue(url,headers) VALUES ('https://old.invalid/send','{"Authorization":"fixture-only"}');
      CREATE TABLE public.listings(id integer PRIMARY KEY);
      CREATE TABLE public.local_audit(id integer);
      CREATE TABLE public.email_jobs(id integer PRIMARY KEY, payload jsonb, status text);
      INSERT INTO public.email_jobs VALUES (1,'{"to":"fixture@example.invalid"}','queued');
      CREATE FUNCTION public.dispatch_hot_sheet_listing(p_id integer) RETURNS void SECURITY DEFINER LANGUAGE plpgsql AS $$
        BEGIN PERFORM net.http_post('https://old.invalid/send'); END; $$;
      CREATE FUNCTION public.invoke_worker() RETURNS bigint LANGUAGE sql AS $$
        SELECT net.http_post('https://old.invalid/worker'); $$;
      CREATE PROCEDURE public.direct_send() LANGUAGE plpgsql AS $$
        BEGIN PERFORM net.http_post('https://old.invalid/send'); END; $$;
      CREATE FUNCTION business.table_send(a integer DEFAULT 7) RETURNS TABLE(result bigint) LANGUAGE sql AS $$
        SELECT net.http_post('https://old.invalid/send'); $$;
      CREATE FUNCTION public.quoted_send() RETURNS bigint LANGUAGE sql AS $$
        SELECT "net"."http_post"('https://old.invalid/send'); $$;
      CREATE FUNCTION public.local_only() RETURNS integer LANGUAGE sql AS 'SELECT 7';
      CREATE FUNCTION supabase_functions.http_request() RETURNS trigger LANGUAGE plpgsql AS $$
        BEGIN PERFORM net.http_post('https://old.invalid/webhook'); RETURN NEW; END; $$;
      CREATE TRIGGER direct_http AFTER INSERT ON public.listings FOR EACH ROW
        EXECUTE FUNCTION supabase_functions.http_request();
      CREATE FUNCTION public.indirect_listing_trigger() RETURNS trigger LANGUAGE plpgsql AS $$
        BEGIN
          INSERT INTO public.local_audit VALUES(NEW.id);
          BEGIN PERFORM public.dispatch_hot_sheet_listing(NEW.id); EXCEPTION WHEN OTHERS THEN NULL; END;
          RETURN NEW;
        END; $$;
      CREATE TRIGGER indirect_http AFTER INSERT ON public.listings FOR EACH ROW
        EXECUTE FUNCTION public.indirect_listing_trigger();
    `);
    const status = async () => (await db.query('SELECT public.migration_no_contact_status() AS status')).rows[0].status;

    await t.test('unconfigured target is refused before any mutation', async () => {
      await assert.rejects(db.exec(script), /Edit confirm_target/);
      await db.exec('ROLLBACK');
      assert.equal((await db.query('SELECT active FROM cron.job WHERE jobid=1')).rows[0].active, true);
    });

    await t.test('legacy project confirmation is refused', async () => {
      await assert.rejects(db.exec(script.replace('REPLACE_WITH_NEW_PROJECT_REF','qocduqtfbsevnhlgsfka')), /Edit confirm_target/);
      await db.exec('ROLLBACK');
    });

    await t.test('cron, SQL networking, direct webhooks and pending HTTP are quarantined', async () => {
      await db.exec(lock);
      const result = await status();
      assert.equal(result.database_locked, true);
      assert.equal(result.target_project_ref, ref);
      assert.equal(result.active_cron_jobs, 0);
      assert.equal(result.queued_http_requests, 0);
      assert.equal(result.unguarded_network_routines, 0);
      assert.equal(result.active_http_triggers, 0);
      assert.equal(result.changed_quarantined_routines, 0);
      assert.equal(result.quarantined_routines, 5);
      assert.equal((await db.query("SELECT tgenabled FROM pg_trigger WHERE tgname='direct_http'")).rows[0].tgenabled, 'D');
    });

    await t.test('scalar, table-returning and procedure dispatch fail without any network queue insert', async () => {
      for (const query of ['SELECT public.invoke_worker()', 'SELECT public.dispatch_hot_sheet_listing(9)',
        'SELECT * FROM business.table_send()', 'SELECT public.quoted_send()', 'CALL public.direct_send()']) {
        await assert.rejects(db.exec(query), /MIGRATION_OUTBOUND_BLOCKED/);
      }
      assert.equal((await db.query('SELECT count(*)::int AS count FROM net.http_request_queue')).rows[0].count, 0);
    });

    await t.test('unrelated business logic remains, and business email queues are preserved', async () => {
      await db.exec('INSERT INTO public.listings VALUES (1)');
      assert.equal((await db.query('SELECT count(*)::int AS count FROM public.local_audit')).rows[0].count, 1);
      assert.equal((await db.query('SELECT public.local_only() AS result')).rows[0].result, 7);
      assert.equal((await db.query('SELECT count(*)::int AS count FROM public.email_jobs')).rows[0].count, 1);
      assert.equal((await db.query('SELECT count(*)::int AS count FROM net.http_request_queue')).rows[0].count, 0);
    });

    await t.test('original configuration is preserved and reapplying is idempotent', async () => {
      const original = (await db.query('SELECT definition FROM migration_safety.function_backup ORDER BY signature')).rows;
      await db.exec(lock);
      assert.deepEqual((await db.query('SELECT definition FROM migration_safety.function_backup ORDER BY signature')).rows, original);
      assert.equal((await db.query('SELECT (job_data->>\'active\')::boolean AS active FROM migration_safety.cron_backup WHERE jobid=1')).rows[0].active, true);
      assert.equal((await db.query('SELECT count(*)::int AS count FROM migration_safety.http_queue_backup')).rows[0].count, 1);
      assert.equal((await status()).database_locked, true);
    });

    await t.test('anonymous users can read counts but not saved credentials or definitions', async () => {
      await db.exec('SET ROLE anon');
      assert.equal((await status()).database_locked, true);
      for (const name of ['function_backup','cron_backup','http_queue_backup','state']) {
        await assert.rejects(db.query(`SELECT * FROM migration_safety.${name}`), /permission denied/);
      }
      await db.exec('RESET ROLE');
    });

    await t.test('reenabled cron is detected and re-lock restores the paused state', async () => {
      await db.exec('UPDATE cron.job SET active=true WHERE jobid=1');
      assert.equal((await status()).database_locked, false);
      await db.exec(lock);
      assert.equal((await status()).database_locked, true);
    });

    await t.test('new SQL networking after a restore is detected and quarantined on re-lock', async () => {
      await db.exec("CREATE FUNCTION public.newly_restored_sender() RETURNS bigint LANGUAGE sql AS $$ SELECT net.http_post('https://old.invalid/send'); $$");
      assert.equal((await status()).database_locked, false);
      await db.exec(lock);
      assert.equal((await status()).database_locked, true);
      await assert.rejects(db.query('SELECT public.newly_restored_sender()'), /MIGRATION_OUTBOUND_BLOCKED/);
    });

    await t.test('changes to an existing guard make status fail even without recognizable HTTP text', async () => {
      await db.exec('CREATE OR REPLACE FUNCTION public.invoke_worker() RETURNS bigint LANGUAGE sql AS $$ SELECT 1::bigint; $$');
      const result = await status();
      assert.equal(result.database_locked, false);
      assert.equal(result.changed_quarantined_routines, 1);
    });
  } finally { await db.close(); }
});
